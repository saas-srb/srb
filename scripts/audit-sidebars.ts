/**
 * P0 audit (read-only): every menu item in every product's own sidebar, with the gate expression written next to it (text scan of the
 * *Sidebar.tsx files). This is the UI-level feature list (what a person can click) and the legacy guard each item sits behind.
 *   npx tsx scripts/audit-sidebars.ts [--write]   (writes docs/commandos-audit-sidebars.md)
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const COMP = join(process.cwd(), "src", "components", "products");
const out = ["# CommandOS audit: product sidebars, item by item (generated, P0)", "", "Generated by `npx tsx scripts/audit-sidebars.ts --write`. Each product has its own `*Sidebar.tsx` (plus a Shell and a Mobile copy). The **gate** column is the condition written next to the item (`-` = always shown to anyone who can open the product, or filtered elsewhere).", ""];
let total = 0;
const rows: Record<string, { label: string; href: string; gate: string; line: number }[]> = {};
for (const dir of readdirSync(COMP)) {
  const d = join(COMP, dir);
  if (!statSync(d).isDirectory()) continue;
  for (const f of readdirSync(d)) {
    if (!/Sidebar\.tsx$/.test(f) || /Mobile|Shell/.test(f)) continue;
    const lines = readFileSync(join(d, f), "utf8").split("\n");
    lines.forEach((l, i) => {
      const href = /href:\s*["'`]([^"'`]+)["'`]/.exec(l)?.[1];
      const label = /label:\s*["'`]([^"'`]+)["'`]/.exec(l)?.[1];
      if (!href || !label) return;
      const gate = /\{\s*([^{}]*?)\s*&&\s*nav\(/.exec(l)?.[1] ?? (/\?\s*nav\(|isStaff\s*&&|isEmployee/.test(l) ? "role-based ternary" : "-");
      (rows[`${dir} (${f})`] ??= []).push({ label, href, gate, line: i + 1 });
      total++;
    });
  }
}
out.push(`${total} menu items found in ${Object.keys(rows).length} sidebars.`, "");
for (const [k, items] of Object.entries(rows)) {
  out.push(`## ${k}`, "", "| Item | Path | Gate | Line |", "| --- | --- | --- | --- |");
  for (const i of items) out.push(`| ${i.label} | \`${i.href}\` | ${i.gate === "-" ? "-" : "`" + i.gate.replace(/\|/g, "/") + "`"} | ${i.line} |`);
  out.push("");
}
// Feature areas by page folder: the first path segment under each product (pages counted), for products whose sidebar is built from data.
const APP = join(process.cwd(), "src", "app", "(products)");
out.push("# Feature areas by page folder (every product)", "", "| Product | Area (first folder) | Pages |", "| --- | --- | --- |");
const walk = (d: string, base: string, acc: Map<string, number>) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p, base, acc); else if (f === "page.tsx") { const rel = p.slice(base.length + 1).split("/").filter((x) => !/^\(.*\)$/.test(x)); const area = rel.length > 1 ? rel[0] : "(root)"; acc.set(area, (acc.get(area) ?? 0) + 1); } } };
for (const prod of readdirSync(APP).filter((x) => statSync(join(APP, x)).isDirectory() && x !== "api").sort()) {
  const acc = new Map<string, number>();
  walk(join(APP, prod), join(APP, prod), acc);
  for (const [area, n] of [...acc].sort((a, b) => b[1] - a[1])) out.push(`| ${prod} | ${area} | ${n} |`);
}
const text = out.join("\n");
if (process.argv.includes("--write")) writeFileSync("docs/commandos-audit-sidebars.md", text); else console.log(text);
console.error(`${total} items in ${Object.keys(rows).length} sidebars`);
