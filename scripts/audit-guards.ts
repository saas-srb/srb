/**
 * P0 audit (read-only): how each product enforces access today, by scanning source text. For every product it counts pages, layouts, API route
 * handlers and server-action files, and how many of them contain an access check; it lists the ones that do not (input of the P8 sweep) and the
 * layouts/pages where a person's ROLE changes the UI (input of R9). Heuristic (text scan), meant for review, not as proof.
 *   npx tsx scripts/audit-guards.ts [--write]   (writes docs/commandos-audit-guards.md)
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const APP = join(process.cwd(), "src", "app");
const PRODUCTS = ["talentos", "sprintos", "dealflow-ai", "cashflow-ai", "spendiq", "cohort-ai", "huddle-ai", "playbook-ai", "contractflow-ai", "cybervault", "evaliq", "agentos", "databrain-ai", "viralpulse-ai", "rankmax-ai", "sitecraft-ai", "clientos", "resolveiq", "commandos"];
const GUARD = /\brequire\w*(User|Access|Action|Session|Staff|Admin|Permission)\w*\(|\b\w+Can\(|\bcan[A-Z]\w+\(|\bhas\w+(Access|Role)\w*\(|resolvePermission\(|isAuthorized\w*\(|getSession\w+\(|getCurrent\w*User\(|verify\w+(Token|Signature|Secret)\w*\(|hasBearer\(|withTransport\(|authorize\w*\(|\bcheckPlatformPermission\(|\bassert\w*Access\w*\(/;
const PUBLIC_OK = /\/(login|register|invite|forgot-password|reset-password|public|share|embed|webhook|callback|cron|signup|apply|verify|sign|pay|opengraph|sitemap|robots|manifest|icon)\b/i;
const ROLE_UI = /\b(isEmployeeOnly|isStudentOnly|isPmsEmployeeOnly|hasStaffRole|hasPmsStaffRole|hasTmsStaffRole|hasPrmsStaffRole|hasChatStaffRole|isLpmsManagerTier|isDlmsManagerTier|isAibotsManagerTier|isSopManagerTier|isSopAdmin|isFmsAdmin|isPmsAdmin|isTmsAdmin|isPrmsAdmin|isLmsAdmin|isHrmsAdmin|primary\w+RoleLabel|roleHome)\b|roles\.includes\(["'][a-z_]+["']\)|redirect\(["'`]\/[a-z-]+\/me["'`]/;

function* walk(d: string): Generator<string> {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (/\.(tsx?|ts)$/.test(f)) yield p;
  }
}
const productOf = (rel: string): string | null => {
  const parts = rel.split("/").filter((s) => !/^\(.*\)$/.test(s));
  if (parts[0] === "api") return PRODUCTS.find((p) => p === parts[1]) ?? (parts[1] === "talentos" ? "talentos" : null);
  return PRODUCTS.find((p) => p === parts[0]) ?? null;
};

interface Row { rel: string; kind: "page" | "layout" | "route" | "actions"; guarded: boolean; roleUi: boolean }
const rows = new Map<string, Row[]>();
for (const file of walk(APP)) {
  const rel = relative(APP, file);
  const base = file.split("/").pop()!;
  const kind: Row["kind"] | null = base === "page.tsx" ? "page" : base === "layout.tsx" ? "layout" : /^route\.tsx?$/.test(base) ? "route" : null;
  const text = readFileSync(file, "utf8");
  const isActions = /^\s*["']use server["']/.test(text.slice(0, 300));
  const k = kind ?? (isActions ? "actions" : null);
  if (!k) continue;
  const prod = productOf(rel) ?? "(platform and shared)";
  (rows.get(prod) ?? rows.set(prod, []).get(prod)!).push({ rel, kind: k, guarded: GUARD.test(text), roleUi: ROLE_UI.test(text) });
}

const out: string[] = ["# CommandOS audit: where access is enforced today (generated, P0)", "", "Generated by `npx tsx scripts/audit-guards.ts --write`: a text scan of `src/app`. A file counts as **guarded** when it calls a known access helper (`requireXUser`, `xCan`, `canX`, `hasXAccess`, `resolvePermission`, `getSessionXUser`, a bearer/signature check ...). Pages that sit under a guarded layout can be fine without their own check, so the *unguarded* lists are the input of the P8 sweep, not a verdict.", ""];
out.push("| Product | pages | layouts | API routes | action files | guarded pages | guarded routes | guarded actions | files that branch on a role (UI) |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
const keys = [...rows.keys()].sort();
let tot = { p: 0, l: 0, r: 0, a: 0, gp: 0, gr: 0, ga: 0, ui: 0 };
for (const k of keys) {
  const rs = rows.get(k)!;
  const c = (kind: Row["kind"]) => rs.filter((r) => r.kind === kind);
  const g = (kind: Row["kind"]) => c(kind).filter((r) => r.guarded).length;
  const ui = rs.filter((r) => r.roleUi).length;
  out.push(`| ${k} | ${c("page").length} | ${c("layout").length} | ${c("route").length} | ${c("actions").length} | ${g("page")} | ${g("route")} | ${g("actions")} | ${ui} |`);
  tot = { p: tot.p + c("page").length, l: tot.l + c("layout").length, r: tot.r + c("route").length, a: tot.a + c("actions").length, gp: tot.gp + g("page"), gr: tot.gr + g("route"), ga: tot.ga + g("actions"), ui: tot.ui + ui };
}
out.push(`| **Total** | ${tot.p} | ${tot.l} | ${tot.r} | ${tot.a} | ${tot.gp} | ${tot.gr} | ${tot.ga} | ${tot.ui} |`, "");
out.push("## API routes and action files without a recognised access check", "", "(Public by design: sign-in, webhooks with signatures, public forms, cron with bearer; those are matched by name and marked `public?`.)", "");
for (const k of keys) {
  const bad = rows.get(k)!.filter((r) => (r.kind === "route" || r.kind === "actions") && !r.guarded);
  if (!bad.length) continue;
  out.push(`### ${k} (${bad.length})`, "", ...bad.map((r) => `- \`${r.rel}\`${PUBLIC_OK.test(r.rel) ? " (public?)" : ""}`), "");
}
out.push("## Files where a person's ROLE changes what the UI shows (R9 input)", "");
for (const k of keys) {
  const ui = rows.get(k)!.filter((r) => r.roleUi);
  if (!ui.length) continue;
  out.push(`### ${k} (${ui.length})`, "", ...ui.map((r) => `- \`${r.rel}\` (${r.kind})`), "");
}
const text = out.join("\n");
if (process.argv.includes("--write")) writeFileSync("docs/commandos-audit-guards.md", text);
else console.log(text);
console.error(`pages ${tot.p}, layouts ${tot.l}, routes ${tot.r}, action files ${tot.a}; role-branching files ${tot.ui}`);
