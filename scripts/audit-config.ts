/**
 * P0 audit (read-only): every configuration / settings / integration page in src/app and what it reads and writes, from its imports.
 * For each page directory it lists the `@/lib/...` modules imported by the page and its sibling files, the Mongo collections those modules
 * touch (text scan for collection("..."), and the server keys they resolve (getConfig / connectionValues / process.env). Used to find duplicates.
 *   npx tsx scripts/audit-config.ts [--write]  (writes docs/commandos-audit-config.md)
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const ROOT = process.cwd();
const APP = join(ROOT, "src", "app");
const SRC = join(ROOT, "src");
const RE_PAGE = /(^|\/)(settings|config|integrations?|connections?|preferences|webhooks?|branding|email|sms|whatsapp|voice|push|chatbot|automations|phone|publishing|domains|apps?|payment-methods|payments|emails)(\/|$)/i;

function* walk(d: string): Generator<string> {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (/page\.tsx$/.test(f)) yield p;
  }
}
const resolveLib = (spec: string): string | null => {
  if (!spec.startsWith("@/")) return null;
  const base = join(SRC, spec.slice(2));
  for (const e of [".ts", ".tsx", "/index.ts", "/index.tsx", ""]) if (existsSync(base + e) && statSync(base + e).isFile()) return base + e;
  return null;
};
const importsOf = (file: string): string[] => [...readFileSync(file, "utf8").matchAll(/from\s+["'](@\/[^"']+)["']/g)].map((m) => m[1]);
function closure(entries: string[], depth = 2): Set<string> {
  const seen = new Set<string>();
  let frontier = entries;
  for (let i = 0; i <= depth; i++) {
    const next: string[] = [];
    for (const f of frontier) {
      if (seen.has(f)) continue;
      seen.add(f);
      if (!/\.(ts|tsx)$/.test(f)) continue;
      for (const s of importsOf(f)) { const r = resolveLib(s); if (r && r.includes("/lib/")) next.push(r); }
    }
    frontier = next;
  }
  return seen;
}

interface Row { page: string; libs: string[]; collections: string[]; keys: string[]; siblings: number }
const rows: Row[] = [];
for (const page of walk(APP)) {
  const rel = relative(APP, dirname(page));
  if (!RE_PAGE.test(rel) || /(platform)\/(saas|console)/.test(rel)) continue;
  const dir = dirname(page);
  const files = readdirSync(dir).filter((f) => /\.(tsx?|ts)$/.test(f)).map((f) => join(dir, f));
  const libs = [...closure(files, 1)].filter((f) => f.includes("/lib/")).map((f) => relative(SRC, f));
  const colls = new Set<string>(), keys = new Set<string>();
  for (const l of libs) {
    const text = readFileSync(join(SRC, l), "utf8");
    for (const m of text.matchAll(/collection(?:<[^>]*>)?\(\s*["'`]([a-z0-9_\.]+)["'`]/gi)) colls.add(m[1]);
    for (const m of text.matchAll(/(?:getConfig|getConfigs)\(\s*\[?\s*["']([A-Z0-9_]+)["']/g)) keys.add(m[1]);
    for (const m of text.matchAll(/connectionValues\(\s*["']([a-z\-]+)["']/g)) keys.add(`connection:${m[1]}`);
    for (const m of text.matchAll(/process\.env\.([A-Z][A-Z0-9_]+)/g)) if (!/^(NODE_ENV|NEXT_RUNTIME|VERCEL|PORT)$/.test(m[1])) keys.add(`env:${m[1]}`);
  }
  rows.push({ page: rel, libs: libs.filter((l) => /(settings|config|integration|connection|email|sms|push|chatbot|voice|payment|brand|domain|notif|prompt|schedule)/i.test(l)).slice(0, 8), collections: [...colls].sort().slice(0, 12), keys: [...keys].sort().slice(0, 10), siblings: files.length });
}
rows.sort((a, b) => a.page.localeCompare(b.page));
const out = ["# CommandOS audit: configuration pages and what they touch (generated, P0)", "", `Generated by \`npx tsx scripts/audit-config.ts --write\`: ${rows.length} settings/config/integration pages found under src/app (platform Console and the public site excluded). Libs are the settings-related modules the page imports (2 levels); collections and keys are text-scanned from those modules.`, "", "| Page | Settings libs it imports | Collections touched | Server keys / env it resolves |", "| --- | --- | --- | --- |"];
for (const r of rows) out.push(`| \`/${r.page.replace(/\((\w+)\)\/?/g, "").replace(/\(protected\)\/?|\(staff\)\/?|\(app\)\/?/g, "")}\` | ${r.libs.map((l) => "`" + l.replace("lib/", "") + "`").join("<br>") || "-"} | ${r.collections.map((c) => "`" + c + "`").join(", ") || "-"} | ${r.keys.join(", ") || "-"} |`);
const text = out.join("\n");
if (process.argv.includes("--write")) writeFileSync("docs/commandos-audit-config.md", text); else console.log(text);
console.error(`${rows.length} pages`);
