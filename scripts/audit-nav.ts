/**
 * P0 audit (read-only): today's CommandOS navigation as a Director sees it (resolveNav with super_admin and every product on), by section and group,
 * with whether the sidebar lists the section. Prints markdown. npx tsx scripts/audit-nav.ts [--write]  (writes docs/commandos-audit-nav.md)
 */
import { writeFileSync } from "node:fs";
import { NAV_KEYS, NAV_SECTIONS, resolveNav } from "../src/lib/products/commandos/nav";

const nav = resolveNav({ user: { roles: ["super_admin"], permissionOverrides: null }, platformAccess: true });
const out = ["# CommandOS audit: current navigation as the Director sees it (generated, P0)", "", `Generated by \`npx tsx scripts/audit-nav.ts --write\`. ${NAV_KEYS.length} nav items defined, ${nav.allowed.length} open for a Director.`, ""];
out.push("| Section | Listed in sidebar | Items |", "| --- | --- | --- |");
for (const s of NAV_SECTIONS) {
  const sec = nav.sections.find((x) => x.key === s.key);
  out.push(`| ${s.label || "(dashboard)"} \`${s.key}\` | ${s.sidebar === false ? "NO (sidebar:false)" : "yes"} | ${sec?.items.length ?? 0} |`);
}
out.push("");
for (const sec of nav.sections) {
  out.push(`## ${sec.label || "Dashboard"} (\`${sec.key}\`)${sec.sidebar ? "" : " - not listed in the sidebar"}`, "");
  const groups = new Map<string, typeof sec.items>();
  for (const i of sec.items) (groups.get(i.group ?? "") ?? groups.set(i.group ?? "", []).get(i.group ?? "")!).push(i);
  for (const [g, items] of groups) {
    if (g) out.push(`**${g}**`, "");
    for (const i of items) out.push(`- ${i.label} - \`${i.href}\`${i.external ? " (new tab)" : ""}`);
    out.push("");
  }
}
const text = out.join("\n");
if (process.argv.includes("--write")) writeFileSync("docs/commandos-audit-nav.md", text); else console.log(text);
console.error(`${NAV_KEYS.length} items; sections: ${nav.sections.map((s) => `${s.key}=${s.items.length}`).join(", ")}`);
